/* Writes prisma/postgres/schema.prisma: the same data model as prisma/schema.prisma, for PostgreSQL.
   Prisma cannot pick the database type from an environment variable, so the Postgres copy is generated
   from the main schema. Edit prisma/schema.prisma only; this file is regenerated by the pg:* scripts. */
const fs = require('fs');
const path = require('path');

const src = path.join(__dirname, '..', 'prisma', 'schema.prisma');
const outDir = path.join(__dirname, '..', 'prisma', 'postgres');
const schema = fs.readFileSync(src, 'utf8');
if (!/provider\s*=\s*"sqlite"/.test(schema)) throw new Error('Expected provider = "sqlite" in prisma/schema.prisma');

const pg = schema.replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'schema.prisma'), '// GENERATED from prisma/schema.prisma by scripts/use-postgres.js. Do not edit.\n' + pg);
console.log('Wrote prisma/postgres/schema.prisma');
